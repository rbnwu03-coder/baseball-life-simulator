'use strict';
// Offline build only. Historical JSON + the pure contract; never loads a Match owner.
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const assert = require('node:assert/strict');
const root = path.resolve(__dirname, '../..');
const contractPath = 'contracts/ss-decision-resolution-public-presentation-v0.2.cjs';
const fixturePath = 'prototype/match-ui-p1/fixture.js';
const evidencePath = 'docs/match-ui-slice-data-contract-v0.1-evidence.json';
const factsPath = 'docs/ss-strategic-scenario-fixture-pa-ledger-integration-v0.1-findings-evidence.json';
const foundationPath = 'docs/ss-decision-resolution-public-presentation-contract-v0.2-evidence.json';
const outputPath = path.join(__dirname, 'presentation-v02.generated.js');
const hash = file => crypto.createHash('sha256').update(fs.readFileSync(path.join(root, file))).digest('hex');
const read = file => JSON.parse(fs.readFileSync(path.join(root, file), 'utf8'));

function generate() {
  const foundation = read(foundationPath);
  const expected = Object.fromEntries([...foundation.sourceEvidence, ...foundation.artifacts].map(x => [x.file, x.sha256]));
  for (const file of [contractPath, evidencePath, factsPath]) assert.equal(hash(file), expected[file], 'Changed historical source: ' + file);
  assert.equal(hash(fixturePath), foundation.integrity.existingReadableHashes[fixturePath]);
  const contract = require(path.join(root, contractPath));
  const fixture = require('./fixture.js');
  const v01 = read(evidencePath), facts = read(factsPath);
  assert.deepEqual(fixture, v01.examples);
  const before = facts.threeTimes.decisionBefore, completed = facts.publicDecision.newCompleted[0];
  const ids = { presentationId: fixture.decision.presentationId, matchId: before.matchId, momentId: before.currentMomentId };
  const stateOf = value => ({ outs: value.outs, scores: { ...value.scores }, bases: value.runners.map(Boolean) });
  const decisionConfirmation = { ...ids, phase: 'decision', admitted: facts.lifecycleBefore.admission.admittedToPlayer,
    lifecycleState: facts.lifecycleBefore.lifecycleState };
  const resultConfirmation = { ...ids, phase: 'resolution', status: 'settled',
    settlementApplied: facts.execution.settlement.settlementApplied, completedMomentId: completed.id,
    selectedRouteId: completed.initialRoute, actualRouteId: completed.activeRoute,
    beforeState: stateOf(before), afterState: stateOf(completed), beforeRunners: before.runners.slice(),
    afterRunners: completed.runners.slice(), batterRunnerId: before.currentBatter,
    outsCreated: completed.outsCreated, scoringRunnerIds: completed.scoringRunnerIds.slice() };
  const decision = contract.createDecisionView(fixture.decision, decisionConfirmation);
  assert.equal(contract.validateDecisionView(decision, fixture.decision, decisionConfirmation), true);
  const resolution = contract.createResolutionView(decision, fixture.resolution, resultConfirmation);
  assert.equal(contract.validateResolutionView(resolution, decision, fixture.resolution, resultConfirmation), true);
  const cache = contract.createReplayCache(decision, resolution);
  assert.strictEqual(cache.replay(), resolution);
  const sourceHashes = Object.fromEntries([contractPath, fixturePath, evidencePath, factsPath, foundationPath,
    'prototype/match-ui-p1/generate-presentation-v02.cjs'].map(file => [file, hash(file)]));
  const provenance = { generator: 'generate-presentation-v02.cjs', sourceHashes,
    validation: ['createDecisionView', 'validateDecisionView', 'createResolutionView', 'validateResolutionView'],
    confirmation: 'Offline declarations derived from recorded admission and applied settlement; not a Production receipt',
    playbackVersion: 'match-ui-slice/0.1', presentationVersion: contract.VERSION };
  // The unchanged CommonJS body is wrapped, not rewritten or bundled. Browser use
  // calls its schema validator only; confirmations are deliberately not shipped.
  const body = fs.readFileSync(path.join(root, contractPath), 'utf8');
  return '/* GENERATED by generate-presentation-v02.cjs; do not hand edit. */\n' +
    '(function (root) {\n"use strict";\nconst contractModule = { exports: {} };\n(function (module) {\n' + body +
    '\n})(contractModule);\nconst contract = contractModule.exports;\n' +
    'const data = ' + JSON.stringify({ decision, resolution }) + ';\n' +
    'const provenance = ' + JSON.stringify(provenance) + ';\n' +
    `function freeze(value) { if (value && typeof value === 'object') { Object.values(value).forEach(freeze); Object.freeze(value); } return value; }
contract.validateSchema(data.decision); contract.validateSchema(data.resolution); freeze(data); freeze(provenance);
const equal = (a, b) => JSON.stringify(a) === JSON.stringify(b);
// Version routing / stream join only. All v0.2 validation above uses the original contract.
function connect(legacy) {
  if (legacy?.decision?.schemaVersion !== 'match-ui-slice/0.1' || legacy?.resolution?.schemaVersion !== 'match-ui-slice/0.1') throw new Error('Expected v0.1 Playback source');
  for (const key of ['presentationId', 'matchId', 'momentId', 'inning', 'half', 'presentationSequence', 'state', 'situationText', 'choices']) {
    if (!equal(legacy.decision[key], data.decision[key])) throw new Error('Decision stream mismatch: ' + key);
  }
  for (const key of Object.keys(legacy.resolution).filter(key => key !== 'schemaVersion')) {
    if (!equal(legacy.resolution[key], data.resolution[key])) throw new Error('Resolution stream mismatch: ' + key);
  }
  return data;
}
const api = Object.freeze({ VERSION: contract.VERSION, provenance, connect });
if (typeof module === 'object' && module.exports) module.exports = api;
else Object.defineProperty(root, 'MATCH_UI_P23_PRESENTATION', { value: api });
})(typeof globalThis !== 'undefined' ? globalThis : this);
`;
}
if (require.main === module) {
  const output = generate();
  if (process.argv.includes('--check')) assert.equal(fs.readFileSync(outputPath, 'utf8'), output, 'Regenerate the v0.2 asset');
  else fs.writeFileSync(outputPath, output, { encoding: 'utf8', flag: 'wx' });
  console.log(process.argv.includes('--check') ? 'v0.2 generated asset matches verified source' : 'v0.2 generated asset created and validated');
}
module.exports = Object.freeze({ generate });
